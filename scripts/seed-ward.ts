async function main() {
  console.log("🌿 Seeding Ward data...");
  try {
    // Clear existing ward data
    await db.delete(schema.dailyWard);
    console.log("✅ Cleared old ward data");

    // Insert new data
    for (const item of wardData) {
      await db.insert(schema.dailyWard).values(item);
    }
    console.log(`✅ Inserted ${wardData.length} ward items`);
  } catch (e) {
    console.error("❌ Error:", e);
    process.exit(1);
  } finally {
    await pool.end();
  }
}

main();
